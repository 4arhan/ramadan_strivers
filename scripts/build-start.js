#!/usr/bin/env node
/* build-start.js — turns content/start.json (the "Start here" content for people new to Islam) and
   content/start-ui.json (its screen labels) into
     js/start-data.js            RS.startData = structure only (ids, icons, references, poses, Arabic, transliteration)
     i18n-src/en/start.json      every English string (st.*), translated like the other i18n-src files
   then run scripts/build-i18n.js. Fails on emoji, missing text, duplicate ids or unknown icons/poses.
   content/start.json: { guide: [{id, icon, title, paras: [..], refs: [{ref, url}]}],
     pray: { intro: [..], wudu: [{id, title, text}], wuduRefs: [..], steps: [{id, pose, title, text, arabic, translit, meaning}], refs: [..], note },
     terms: [{id, term, def}] } */
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const src = JSON.parse(fs.readFileSync(path.join(ROOT, 'content', 'start.json'), 'utf8'));
const ui = JSON.parse(fs.readFileSync(path.join(ROOT, 'content', 'start-ui.json'), 'utf8'));
global.window = {}; eval(fs.readFileSync(path.join(ROOT, 'js', 'icons.js'), 'utf8'));
const ICONS = window.RS.icons, POSES = ['stand', 'hands', 'ruku', 'rise', 'sujood', 'sit', 'salam'];
const EMOJI = /[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}\u{1F000}-\u{1F2FF}\u{2B50}\u{2B55}]/u;
const errs = [], text = Object.assign({}, ui), seen = new Set();
const put = (k, v) => { v = String(v == null ? '' : v).trim(); if (!v) errs.push('empty text: ' + k); if (EMOJI.test(v)) errs.push('emoji in ' + k); if (/—/.test(v)) errs.push('em dash in ' + k); text[k] = v; };
const id = (x, where) => { if (!/^[a-z0-9-]{1,40}$/.test(x || '')) errs.push(where + ': bad id "' + x + '"'); if (seen.has(where + x)) errs.push(where + ': duplicate id ' + x); seen.add(where + x); return x; };
const refs = (list, where) => (list || []).map(r => { if (!r || !r.ref) errs.push(where + ': ref without text'); if (r.url && !/^https:\/\/(quran\.com|sunnah\.com)\//.test(r.url)) errs.push(where + ': unexpected url ' + r.url); return { ref: String(r.ref), url: r.url || '' }; });

const data = { guide: [], pray: { intro: 0, wudu: [], wuduRefs: [], steps: [], refs: [] }, terms: [] };
(src.guide || []).forEach(g => {
  id(g.id, 'guide'); if (!ICONS[g.icon]) errs.push('guide ' + g.id + ': unknown icon ' + g.icon);
  put('st.g.' + g.id + '.t', g.title); (g.paras || []).forEach((p, i) => put('st.g.' + g.id + '.p' + (i + 1), p));
  data.guide.push({ id: g.id, icon: g.icon, n: (g.paras || []).length, refs: refs(g.refs, 'guide ' + g.id) });
});
const P = src.pray || {};
(P.intro || []).forEach((p, i) => put('st.pr.i' + (i + 1), p)); data.pray.intro = (P.intro || []).length;
(P.wudu || []).forEach(w => { id(w.id, 'wudu'); put('st.w.' + w.id + '.t', w.title); put('st.w.' + w.id + '.x', w.text); data.pray.wudu.push(w.id); });
data.pray.wuduRefs = refs(P.wuduRefs, 'wudu');
(P.steps || []).forEach(s => {
  id(s.id, 'step'); if (!POSES.includes(s.pose)) errs.push('step ' + s.id + ': unknown pose ' + s.pose);
  put('st.p.' + s.id + '.t', s.title); put('st.p.' + s.id + '.x', s.text);
  if (s.meaning) put('st.p.' + s.id + '.m', s.meaning);
  data.pray.steps.push({ id: s.id, pose: s.pose, arabic: s.arabic || '', translit: s.translit || '' });
});
data.pray.refs = refs(P.refs, 'pray'); put('st.pr.note', P.note);
(src.terms || []).forEach(t => { id(t.id, 'term'); put('st.term.' + t.id + '.n', t.term); put('st.term.' + t.id + '.d', t.def); data.terms.push(t.id); });

// content/kids.json (optional): { easyTf: [tf ids], stories: [{n, title, text, q, a, ref, url}] } for kids mode
const kidsFile = path.join(ROOT, 'content', 'kids.json');
data.stories = []; data.easyTf = [];
if (fs.existsSync(kidsFile)) {
  const K = JSON.parse(fs.readFileSync(kidsFile, 'utf8'));
  const tfIds = new Set(JSON.parse(fs.readFileSync(path.join(ROOT, 'content', 'tf.json'), 'utf8')).map(q => q.id));
  (K.easyTf || []).forEach(x => { if (!tfIds.has(x)) errs.push('kids easyTf: unknown question ' + x); else data.easyTf.push(x); });
  (K.stories || []).forEach(st => {
    if (!(st.n >= 1 && st.n <= 30)) errs.push('story: bad n ' + st.n);
    put('ks.' + st.n + '.t', st.title); put('ks.' + st.n + '.x', st.text); put('ks.' + st.n + '.q', st.q); put('ks.' + st.n + '.a', st.a);
    data.stories.push({ n: st.n, ref: String(st.ref || ''), url: refs([{ ref: st.ref || '-', url: st.url }], 'story ' + st.n)[0].url });
  });
  data.stories.sort((x, y) => x.n - y.n);
}
if (errs.length) { console.error(errs.join('\n')); process.exit(1); }
fs.writeFileSync(path.join(ROOT, 'js', 'start-data.js'), '/* Generated by scripts/build-start.js from content/start.json. Do not edit by hand. */\nwindow.RS = window.RS || {};\nRS.startData = ' + JSON.stringify(data) + ';\n');
fs.writeFileSync(path.join(ROOT, 'i18n-src', 'en', 'start.json'), JSON.stringify(text, null, 2) + '\n');
console.log('start: ' + data.guide.length + ' chapters, ' + data.pray.wudu.length + ' wudu steps, ' + data.pray.steps.length + ' prayer steps, ' + data.terms.length + ' terms, ' + data.stories.length + ' stories, ' + data.easyTf.length + ' easy questions, ' + Object.keys(text).length + ' strings');
