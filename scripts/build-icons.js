#!/usr/bin/env node
/* =====================================================================================================
   build-icons.js — writes js/icons.js (RS.icons, the line-icon sprite) from Lucide's SVG files (ISC licence).

   Usage:  node scripts/build-icons.js [path/to/lucide-static]
           (default: ./node_modules/lucide-static — e.g. `npm i --no-save lucide-static` first; not a dependency)

   Design rules (DESIGN.md §1, §7) enforced here:
   - never a sparkle/sparkles, party-popper (confetti) or similar celebration icon — use gift, moon or calendar-check;
   - moon-star is the one allowed exception, kept ONLY for last-ten-nights / Laylat al-Qadr content (its small
     "+" twinkle reads as a sparkle at kicker size): use moon for Ramadan kickers, nav and generic night icons.
   core.js maps a removed name (party-popper, sparkle, sparkles) to an allowed icon and warns once.
   ===================================================================================================== */
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const LUCIDE = path.resolve(process.argv[2] || path.join(ROOT, 'node_modules', 'lucide-static'));
const OUT = path.join(ROOT, 'js', 'icons.js');
const NAMES = [
  // required set
  'sun', 'moon', 'moon-star', 'sunrise', 'sunset', 'book-open', 'book-heart', 'graduation-cap', 'trophy', 'user', 'users',
  'user-plus', 'check', 'circle-check', 'check-check', 'badge-check', 'chevron-left', 'chevron-right', 'chevron-down',
  'arrow-right', 'arrow-left', 'arrow-up-right', 'clock', 'timer', 'hourglass', 'flame', 'star', 'award', 'medal', 'crown',
  'calendar', 'calendar-check', 'chart-column', 'hand-heart', 'hand-helping', 'heart', 'shield', 'school', 'building-2',
  'landmark', 'settings', 'sliders-horizontal', 'languages', 'globe', 'bell', 'share-2', 'download', 'upload', 'printer',
  'qr-code', 'link', 'copy', 'external-link', 'x', 'plus', 'minus', 'refresh-cw', 'rotate-ccw', 'repeat', 'shuffle',
  'log-in', 'log-out', 'mail', 'lock', 'info', 'circle-help', 'triangle-alert', 'trash-2', 'pencil', 'eye', 'eye-off',
  'list', 'layers', 'target', 'compass', 'map-pin', 'droplets', 'utensils', 'search', 'play', 'message-circle', 'gift',
  'sprout', 'notebook-pen', 'footprints', 'file-text', 'scroll-text', 'circle-x', 'circle-dot', 'cloud', 'wifi-off',
  // extras used by the shell / likely needed by modules
  'chevron-up', 'house', 'ellipsis', 'flower-2', 'bell-ring', 'cloud-off', 'calendar-days', 'list-checks', 'chart-line',
  'smartphone', 'send', 'key-round', 'user-check', 'circle', 'heart-handshake', 'book-marked', 'brain', 'navigation',
  'palette', 'swatch-book', 'square-pen', 'book-check', 'circle-alert', 'lightbulb', 'lock-open',
  'mic', 'volume-2', 'headphones', 'arrow-down', 'arrow-up', 'grip-horizontal', 'filter', 'circle-plus', 'circle-minus',
  'user-round', 'pause', 'skip-forward', 'shield-check', 'scale', 'leaf', 'baby', 'mountain', 'route', 'sun-moon'
];
const FORBIDDEN = /sparkle|party|confetti|firework|balloon/;
if (!fs.existsSync(path.join(LUCIDE, 'icons'))) { console.error('lucide-static not found at ' + LUCIDE); process.exit(1); }
const icons = {};
const missing = [];
for (const name of NAMES) {
  if (FORBIDDEN.test(name)) throw new Error('forbidden icon (design rule): ' + name);
  const f = path.join(LUCIDE, 'icons', name + '.svg');
  if (!fs.existsSync(f)) { missing.push(name); continue; }
  const src = fs.readFileSync(f, 'utf8');
  const m = src.match(/<svg[^>]*>([\s\S]*?)<\/svg>/);
  if (!m) throw new Error('cannot parse ' + name);
  icons[name] = m[1].replace(/<!--[\s\S]*?-->/g, '').replace(/\s*\n\s*/g, '').replace(/\s+\/>/g, '/>').trim();
}
if (missing.length) console.error('MISSING icons (skipped):', missing.join(', '));
const version = JSON.parse(fs.readFileSync(path.join(LUCIDE, 'package.json'), 'utf8')).version;
const licence = fs.readFileSync(path.join(LUCIDE, 'LICENSE'), 'utf8').trim().split('\n').map(l => ' * ' + l).join('\n').replace(/ +$/gm, '');
const body = Object.keys(icons).sort().map(k => '  ' + JSON.stringify(k) + ': ' + JSON.stringify(icons[k])).join(',\n');
const out = `/*
 * Ramadan Strivers — RS.icons: line-icon sprite (inner SVG markup per icon, 24x24 viewBox).
 * Generated by scripts/build-icons.js from lucide-static v${version} (https://lucide.dev). Do not edit by hand: add the
 * Lucide name to the list in scripts/build-icons.js and regenerate. core.js mounts these as <symbol id="i-NAME">
 * and RS.icon(name) uses them.
 * Design rules: never add a sparkle/sparkles, party-popper (confetti) or similar celebration icon (use gift, moon or
 * calendar-check). moon-star is the one exception, reserved for last-ten-nights / Laylat al-Qadr content; use moon
 * for Ramadan kickers, the nav and generic night icons.
 *
 * Lucide licence:
${licence}
 */
(function () {
  'use strict';
  var RS = window.RS = window.RS || {};
  RS.icons = {
${body}
  };
  if (typeof RS.mountIcons === 'function') RS.mountIcons();
})();
`;
fs.writeFileSync(OUT, out);
console.log('wrote js/icons.js:', Object.keys(icons).length, 'icons,', out.length, 'bytes');
